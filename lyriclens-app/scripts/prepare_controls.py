"""Create original silent/tone negative controls with empty references."""
import hashlib
import json
import math
import struct
import wave
from pathlib import Path


def main():
    root=Path(__file__).resolve().parents[1]/'evaluation'
    folder=root/'audio'/'controls'
    folder.mkdir(parents=True,exist_ok=True)
    rows=[]
    for name in ['silence','tone']:
        target=folder/f'{name}.wav'
        samples=[0 if name=='silence' else int(3000*math.sin(2*math.pi*220*n/16000)) for n in range(16000*5)]
        with wave.open(str(target),'wb') as audio:
            audio.setparams((1,2,16000,0,'NONE','not compressed'))
            audio.writeframes(struct.pack('<'+'h'*len(samples),*samples))
        rows.append({'id':f'negative-{name}','path':str(target.relative_to(root)).replace('\\','/'),
                     'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'language':'en','reference':'',
                     'reference_source':'Original deterministic signal generated by scripts/prepare_controls.py; no vocal content',
                     'permissions':'Original generated fixture; CC0-1.0','duration':5,'conditions':f'{name}; no words; negative control',
                     'language_switching':False,'split':'development','content_type':'negative-control'})
    (root/'controls.jsonl').write_text('\n'.join(json.dumps(r) for r in rows)+'\n',encoding='utf-8')


if __name__=='__main__':
    main()
